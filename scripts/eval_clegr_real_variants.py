#!/usr/bin/env python3
"""Zero-shot evaluation of this project's EXISTING synthetic-benchmark-trained
checkpoints (v2 pooled, v3 multi-neighbor, aspect-readout -- no retraining)
against the REAL CLEGR test set generated by scripts/generate_clegr_real.py.

Distinct from scripts/train_clegr_real.py, which trains fresh TEA/GraphToken
FROM SCRATCH on real CLEGR data (validates the architecture/code works on
real data). This script instead asks: do the checkpoints this project spent
the whole v2_clegr_extended_* effort building on the *synthetic* metro
benchmark actually transfer, zero-shot, to the real benchmark they were
modeled on?

Reuses scripts/run_dynamic_eval_variant.py's `_build_backend` (already
handles pooled/multi_neighbor/aspect construction from an existing
exact2x config + checkpoint) rather than re-implementing model construction
here. Scoring/bucketing logic is copied from train_clegr_real.py's `_score`.

Usage:
  CUDA_VISIBLE_DEVICES=<mig-uuid> HF_HOME=... .venv/bin/python \
    scripts/eval_clegr_real_variants.py \
    --config configs/v2_clegr_extended_exact2x_tea.yaml --variant pooled \
    --label tea_v2_zeroshot --gpu-memory-fraction 0.9

  ... --config configs/v2_clegr_extended_exact2x_tea.yaml --variant multi_neighbor \
      --neighbor-checkpoint outputs/v2_clegr_extended_exact2x_tea/multi_neighbor_projector \
      --label tea_v3_zeroshot

  ... --config configs/v2_clegr_extended_exact2x_aspect.yaml --variant aspect \
      --aspect-checkpoint outputs/v2_clegr_extended_aspect/aspect_checkpoint \
      --label tea_aspect_zeroshot
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from graph_modi.config import load_config  # noqa: E402
from graph_modi.schema import AttributedGraph  # noqa: E402
from graph_modi.training import TrainingExample  # noqa: E402
from run_dynamic_eval_variant import _build_backend  # noqa: E402


def _apply_gpu_memory_cap(fraction: float) -> None:
    import torch

    if fraction >= 1.0 or not torch.cuda.is_available():
        return
    torch.cuda.set_per_process_memory_fraction(fraction, device=0)
    print(f"[clegr-zeroshot] capped this process to {fraction:.0%} of GPU memory", flush=True)


def _load_examples(path: Path) -> list[TrainingExample]:
    examples = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            record = json.loads(line)
            examples.append(
                TrainingExample(
                    graph=AttributedGraph.from_dict(record["graph"]),
                    prompt=record["prompt"],
                    answer=record["answer"],
                    example_id=record["example_id"],
                    split=record["split"],
                    metadata=record["metadata"],
                )
            )
    return examples


_BOOL_TRUE = {"true", "yes", "1"}
_BOOL_FALSE = {"false", "no", "0"}


def _normalize(text: str) -> str:
    return re.sub(r"[^\w\s,.-]", "", text.strip().lower())


def _score(gold: str, pred: str) -> bool:
    gold_norm, pred_norm = _normalize(gold), _normalize(pred)
    if gold_norm in _BOOL_TRUE or gold_norm in _BOOL_FALSE:
        pred_bool = pred_norm in _BOOL_TRUE
        gold_bool = gold_norm in _BOOL_TRUE
        return pred_bool == gold_bool and (pred_norm in _BOOL_TRUE or pred_norm in _BOOL_FALSE)
    try:
        return abs(float(gold_norm) - float(re.sub(r"[^\d.\-]", "", pred_norm))) < 1e-6
    except ValueError:
        pass
    if "," in gold:
        gold_set = {item.strip().lower() for item in gold.split(",") if item.strip()}
        pred_set = {item.strip().lower() for item in pred.split(",") if item.strip()}
        return gold_set == pred_set
    return gold_norm == pred_norm


def _evaluate(model, test_examples, batch_size: int, max_new_tokens: int) -> dict[str, Any]:
    rows = []
    for offset in range(0, len(test_examples), batch_size):
        batch = test_examples[offset : offset + batch_size]
        predictions = model.generate_batch(
            graphs=[example.graph for example in batch],
            prompts=[example.prompt for example in batch],
            max_new_tokens=max_new_tokens,
        )
        for example, predicted in zip(batch, predictions, strict=True):
            rows.append(
                {
                    "clegr_type": example.metadata.get("clegr_type"),
                    "clegr_group": example.metadata.get("clegr_group"),
                    "clegr_subgroup": example.metadata.get("clegr_subgroup"),
                    "gold": example.answer,
                    "predicted": predicted,
                    "correct": _score(example.answer, predicted),
                }
            )
        if (offset // batch_size) % 20 == 0:
            done = min(offset + batch_size, len(test_examples))
            running_acc = sum(r["correct"] for r in rows) / len(rows)
            print(f"[clegr-zeroshot] eval {done}/{len(test_examples)} running_acc={running_acc:.4f}", flush=True)

    def _bucket(key: str) -> dict[str, float]:
        groups: dict[str, list[bool]] = defaultdict(list)
        for row in rows:
            groups[str(row[key])].append(row["correct"])
        return {name: sum(vals) / len(vals) for name, vals in sorted(groups.items())}

    overall = sum(row["correct"] for row in rows) / len(rows)
    return {
        "overall_accuracy": overall,
        "n": len(rows),
        "by_type": _bucket("clegr_type"),
        "by_group": _bucket("clegr_group"),
        "by_subgroup": _bucket("clegr_subgroup"),
        "rows": rows,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True, help="existing exact2x config carrying the checkpoint to test")
    parser.add_argument("--variant", choices=["pooled", "multi_neighbor", "aspect"], required=True)
    parser.add_argument("--neighbor-checkpoint", default=None)
    parser.add_argument("--aspect-checkpoint", default=None)
    parser.add_argument("--label", required=True, help="output filename tag")
    parser.add_argument("--data-dir", default="datasets/clegr_real")
    parser.add_argument("--eval-batch-size", type=int, default=16)
    parser.add_argument("--max-new-tokens", type=int, default=32)
    parser.add_argument("--gpu-memory-fraction", type=float, default=0.9)
    parser.add_argument("--output-dir", default="outputs/clegr_real_zeroshot")
    args = parser.parse_args()

    _apply_gpu_memory_cap(args.gpu_memory_fraction)

    config = load_config(Path(args.config))
    print(f"[clegr-zeroshot] building backend: variant={args.variant} config={args.config}", flush=True)
    backend = _build_backend(config, args.variant, args.neighbor_checkpoint, args.aspect_checkpoint)

    print("[clegr-zeroshot] loading real CLEGR test examples...", flush=True)
    test_examples = _load_examples(Path(args.data_dir) / "test.jsonl")
    print(f"[clegr-zeroshot] test={len(test_examples)}", flush=True)

    backend.model.eval()
    import torch

    with torch.no_grad():
        result = _evaluate(backend.model, test_examples, args.eval_batch_size, args.max_new_tokens)

    print(f"\n=== {args.label} on real CLEGR test ({result['n']} examples) ===")
    print("overall_accuracy:", round(result["overall_accuracy"], 4))
    print("by_group:", {k: round(v, 4) for k, v in result["by_group"].items()})
    print("by_subgroup:", {k: round(v, 4) for k, v in result["by_subgroup"].items()})
    for type_name, acc in sorted(result["by_type"].items(), key=lambda kv: -kv[1])[:15]:
        print(f"  {type_name}: {round(acc, 4)}")

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    out_path = output_dir / f"{args.label}.json"
    out_path.write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")
    print(f"[clegr-zeroshot] wrote {out_path}", flush=True)


if __name__ == "__main__":
    main()
