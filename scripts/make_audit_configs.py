"""Generate the configs for the 2026-10 audit runs from the v3 benchmark configs.

Every audit config is a copy of an existing benchmark config with a small, explicit set of
overrides, so nothing else about the setup drifts. Run from the repo root:

    python scripts/make_audit_configs.py
"""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

CONFIGS = Path("configs")
OUT = CONFIGS / "audit"
GT_CKPT_OLD = "outputs/v3_graphtoken/projector/checkpoint-final"
GT_CKPT_E2E = "outputs/v3_graphtoken_e2e/projector/checkpoint-final"
TEA_CKPT = "outputs/v3_tea/projector/checkpoint-final"
SP_CKPT = "outputs/v3_soft_prompt/soft_prompt/checkpoint-final"

# What the audit calls "the free ones": model-free baselines whose scores do not depend on the
# model, so they are computed once instead of in every model's run.
MODEL_FREE = ["tool_solver", "stale_answer", "majority_answer"]
GRAPH_CONDITIONS = [
    "structure_only",
    "frozen_graph_history",
    "oracle_updated_graph",
    "shuffled_graph",
    "graph_once_then_text",
]


def load(name: str) -> dict:
    return yaml.safe_load((CONFIGS / name).read_text())


def write(name: str, cfg: dict, header: str) -> None:
    OUT.mkdir(exist_ok=True)
    text = f"# {header}\n# Generated by scripts/make_audit_configs.py -- edit the generator, not this file.\n"
    (OUT / name).write_text(text + yaml.safe_dump(cfg, sort_keys=False))


def variant(base: str, out: str, header: str, *, model=None, training=None, evaluation=None,
            top=None) -> dict:
    cfg = copy.deepcopy(load(base))
    cfg["output_dir"] = f"outputs/audit/{out}"
    for key, value in (top or {}).items():
        cfg[key] = value
    for section, changes in (("model", model), ("training", training), ("evaluation", evaluation)):
        if changes:
            cfg.setdefault(section, {}).update(changes)
    write(f"{out}.yaml", cfg, header)
    return cfg


def main() -> None:
    # ---- rank 2/3: eval-only checks on trained checkpoints (static QA) -------------------
    for tag, base, ckpt in (
        ("tea", "v3_tea.yaml", TEA_CKPT),
        ("gt_old", "v3_graphtoken.yaml", GT_CKPT_OLD),
        ("gt_e2e", "v3_graphtoken.yaml", GT_CKPT_E2E),
    ):
        variant(base, f"zerognn_{tag}", f"{tag} checkpoint with node embeddings zeroed (task-ID-only check)",
                model={"checkpoint": ckpt, "graph_ablation": "zero_gnn"})
        variant(base, f"amp_{tag}", f"{tag} checkpoint evaluated with GNN+projector under training-matched autocast",
                model={"checkpoint": ckpt}, evaluation={"encoder_autocast": "match_training"})

    # ---- rank 4: text-only baselines with the first-token parser + raw outputs ------------
    variant("v3_exact2x_tea.yaml", "textonly", "question_only / token_matched_history, new parser, raw outputs",
            evaluation={"conditions": ["question_only", "token_matched_history"]})

    # ---- rank 5: GraphToken optimisation pilots (1 epoch each) ----------------------------
    pilot_training = {
        "epochs": 1,
        "learning_rate": 0.001,            # projector
        "gnn_learning_rate_joint": 0.0001,  # GNN
        "lr_schedule": "cosine",
        "warmup_steps": 100,
        "min_lr_ratio": 0.05,
        "eval_every_steps": 200,
        "val_max_examples": 1000,
        "save_every_steps": 250,
    }
    pilots = {
        "pilot_a": ("warmup+cosine, GNN lr 1e-4, GNN dropout 0.0", {"graph_dropout": 0.0}, {}),
        "pilot_b": ("warmup+cosine, GNN lr 1e-4, GNN dropout 0.1", {"graph_dropout": 0.1}, {}),
        "pilot_c": ("pilot A without bf16 mixed precision", {"graph_dropout": 0.0},
                    {"mixed_precision": "no"}),
        "pilot_d": ("pilot A with sum aggregation (keeps node degree)",
                    {"graph_dropout": 0.0, "graph_aggregation": "sum"}, {}),
    }
    for name, (header, model, training) in pilots.items():
        variant("v3_graphtoken.yaml", name, f"GraphToken pilot: {header}",
                model=model, training={**pilot_training, **training})

    # ---- rank 9: task-conditioned, graph-free control (retrained) --------------------------
    variant("v3_tea.yaml", "taskonly", "TEA recipe with node embeddings zeroed: projector sees task id + hops only",
            model={"graph_ablation": "zero_gnn"})

    # ---- TEA with a GNN that is actually pretrained (the contrastive routine used to leave the
    # GNN frozen, so every earlier "TEA" used a random GNN) + extra seeds (rank 10) ----------
    for seed in (42, 43, 44):
        out = f"tea_fixed_s{seed}"
        variant("v3_tea.yaml", out, f"TEA with working contrastive GNN pretraining, seed {seed}",
                model={"gnn_checkpoint": f"outputs/audit/{out}/gnn/gnn.pt"},
                training={"seed": seed}, top={"seed": seed})
        variant("v3_exact2x_tea.yaml", f"{out}_exact2x", f"{out}: multi-turn evaluation",
                model={"gnn_checkpoint": f"outputs/audit/{out}/gnn/gnn.pt",
                       "checkpoint": f"outputs/audit/{out}/projector/checkpoint-final"},
                training={"seed": seed}, top={"seed": seed},
                evaluation={"conditions": GRAPH_CONDITIONS})

    # ---- third audit: one-factor pilots from the collapsed end-to-end recipe (p0) ------------
    # p0 = v3_graphtoken.yaml as run (constant lr 1e-3 for everything, dropout 0.5, bf16, one
    # shared clip), shortened to 1 epoch so the pilots are comparable with one another.
    p0 = {"epochs": 1, "eval_every_steps": 200, "val_max_examples": 1000, "save_every_steps": 250}
    one_factor = {
        "pilot_p0": ("collapsed recipe as run, 1 epoch (reference)", {}, {}),
        "pilot_frozen": ("same recipe but GNN frozen at its seeded random init (TEA architecture); "
                         "the decisive control", {}, {}),
        "pilot_projlr": ("p0 with projector lr 1e-4 (GNN lr stays 1e-3)",
                         {"learning_rate": 0.0001, "gnn_learning_rate_joint": 0.001}, {}),
        "pilot_norm": ("p0 with the graph vector standardised before the projector",
                       {}, {"graph_vector_norm": "standardize"}),
    }
    for name, (header, training, model) in one_factor.items():
        base = "v3_tea.yaml" if name == "pilot_frozen" else "v3_graphtoken.yaml"
        extra_model = dict(model)
        if name == "pilot_frozen":
            extra_model["gnn_init"] = "random"
        cfg = variant(base, name, f"One-factor pilot: {header}", model=extra_model,
                      training={**p0, **training})
        if name == "pilot_frozen":
            cfg["model"].pop("gnn_checkpoint", None)
            write(f"{name}.yaml", cfg, f"One-factor pilot: {header}")

    # ---- GraphToken that works: pilot D's recipe (sum aggregation) for the full 5 epochs ---------
    # Pilot A (mean aggregation) and pilot D differ only in the aggregation, and only D leaves the
    # prior (53% vs 33% static validation after 1 epoch).
    gt_sum_model = {"graph_dropout": 0.0, "graph_aggregation": "sum"}
    gt_sum_training = {"epochs": 5, "learning_rate": 0.001, "gnn_learning_rate_joint": 0.0001,
                       "lr_schedule": "cosine", "warmup_steps": 200, "min_lr_ratio": 0.05,
                       "eval_every_steps": 500, "val_max_examples": 1000, "save_every_steps": 500}
    variant("v3_graphtoken.yaml", "gt_sum", "GraphToken (random-init GNN trained jointly), sum aggregation, 5 epochs",
            model=gt_sum_model, training=gt_sum_training)
    gt_ckpt = "outputs/audit/gt_sum/projector/checkpoint-final"
    variant("v3_exact2x_graphtoken.yaml", "gt_sum_exact2x", "gt_sum: multi-turn evaluation",
            model={**gt_sum_model, "checkpoint": gt_ckpt}, training=gt_sum_training,
            evaluation={"conditions": GRAPH_CONDITIONS})
    variant("v3_exact2x_graphtoken_predfix.yaml", "gt_sum_predfix", "gt_sum: model-written edits",
            model={**gt_sum_model, "checkpoint": gt_ckpt}, training=gt_sum_training)

    warm = yaml.safe_load((OUT / "pilot_d.yaml").read_text())
    warm["output_dir"] = "outputs/audit/gt_warm"
    warm["model"]["gnn_checkpoint"] = "outputs/audit/pre_sum/gnn/gnn.pt"
    write("gt_warm.yaml", warm, "GraphToken warm start: sum-aggregation GNN pretrained contrastively, then trained jointly (pilot D recipe, 1 epoch)")

    # ---- TEA with working pretraining needs a lower projector lr (inputs vary ~10x more) --------
    tea_lr = {"epochs": 1, "eval_every_steps": 200, "val_max_examples": 1000, "save_every_steps": 250}
    for name, lr in (("pilot_tealr_1e4", 0.0001), ("pilot_tealr_3e4", 0.0003)):
        variant("v3_tea.yaml", name, f"TEA (pre_base GNN), projector lr {lr}, 1 epoch",
                model={"gnn_checkpoint": "outputs/audit/pre_base/gnn/gnn.pt"},
                training={**tea_lr, "learning_rate": lr})

    # ---- clean three-way comparison, all with sum aggregation (headline experiments) -------------
    #  tea_sum        frozen pretrained (contrastive) GNN + projector, projector lr 1e-4 (tuned by pilot)
    #  tea_sum_random frozen random GNN + projector (no pretraining control for tea_sum)
    #  gt_sum         random-init GNN trained jointly (done above)
    #  gt_warm_full   pretrained GNN, then trained jointly (pretraining + joint training)
    sum_model = {"graph_dropout": 0.0, "graph_aggregation": "sum"}
    tea_sum_training = {"learning_rate": 0.0001, "eval_every_steps": 500, "val_max_examples": 1000,
                        "save_every_steps": 500}
    def pair(name, header, model, training, base="v3_tea.yaml", exact_base="v3_exact2x_tea.yaml",
             drop_gnn_ckpt=False):
        cfg = variant(base, name, header, model={**sum_model, **model}, training=training)
        if drop_gnn_ckpt:
            cfg["model"].pop("gnn_checkpoint", None)
            write(f"{name}.yaml", cfg, header)
        ck = f"outputs/audit/{name}/projector/checkpoint-final"
        ex = variant(exact_base, f"{name}_exact2x", f"{name}: multi-turn evaluation",
                     model={**sum_model, **model, "checkpoint": ck}, training=training,
                     evaluation={"conditions": GRAPH_CONDITIONS})
        if drop_gnn_ckpt:
            ex["model"].pop("gnn_checkpoint", None)
            write(f"{name}_exact2x.yaml", ex, f"{name}: multi-turn evaluation")
        return cfg
    pair("tea_sum", "TEA, frozen pretrained sum-aggregation GNN, projector lr 1e-4",
         {"gnn_checkpoint": "outputs/audit/pre_sum/gnn/gnn.pt"}, tea_sum_training)
    pair("tea_sum_random", "TEA, frozen RANDOM sum-aggregation GNN (no-pretraining control), projector lr 1e-4",
         {"gnn_init": "random"}, tea_sum_training, drop_gnn_ckpt=True)
    pair("gt_warm_full", "GraphToken warm start (pretrained sum GNN, trained jointly), 5 epochs",
         {"gnn_checkpoint": "outputs/audit/pre_sum/gnn/gnn.pt"}, gt_sum_training,
         base="v3_graphtoken.yaml", exact_base="v3_exact2x_graphtoken.yaml")
    variant("v3_exact2x_graphtoken_predfix.yaml", "gt_warm_full_predfix", "gt_warm_full: model-written edits",
            model={**sum_model, "gnn_checkpoint": "outputs/audit/pre_sum/gnn/gnn.pt",
                   "checkpoint": "outputs/audit/gt_warm_full/projector/checkpoint-final"},
            training=gt_sum_training)
    for seed in (43, 44):
        name = f"gt_sum_s{seed}"
        pair(name, f"GraphToken sum aggregation, seed {seed}", {}, {**gt_sum_training, "seed": seed},
             base="v3_graphtoken.yaml", exact_base="v3_exact2x_graphtoken.yaml")
        for suffix in ("", "_exact2x"):
            cfg = yaml.safe_load((OUT / f"{name}{suffix}.yaml").read_text())
            cfg["seed"] = seed
            write(f"{name}{suffix}.yaml", cfg, f"GraphToken sum aggregation, seed {seed}")

    # ---- aggregation / readout pilots (same recipe as pilot D, 1 epoch; pilot D = 53.0 val) ------
    d_training = {**p0, "learning_rate": 0.001, "gnn_learning_rate_joint": 0.0001, "lr_schedule": "cosine",
                  "warmup_steps": 100, "min_lr_ratio": 0.05}
    variant("v3_graphtoken.yaml", "pilot_mlpagg",
            "Pilot D with a GIN-style per-neighbour MLP before the sum (aggregation sum_mlp)",
            model={"graph_dropout": 0.0, "graph_aggregation": "sum_mlp"}, training=d_training)
    variant("v3_graphtoken.yaml", "pilot_max", "Pilot D with max aggregation (the remaining GraphSAGE aggregator)",
            model={"graph_dropout": 0.0, "graph_aggregation": "max"}, training=d_training)
    variant("v3_graphtoken.yaml", "pilot_mlpproj",
            "Pilot D with a 2-layer MLP projector (hidden 2048), projector lr 3e-4",
            model={"graph_dropout": 0.0, "graph_aggregation": "sum", "projector_num_layers": 2,
                   "projector_hidden_size": 2048},
            training={**d_training, "learning_rate": 0.0003})

    # ---- degree-balanced dataset (data.degree_balance): does anything change? -------------------
    BAL = "datasets/metro_v3_bal"
    def bal(base, name, header, *, model=None, training=None, evaluation=None):
        cfg = variant(base, name, header, model=model, training=training, evaluation=evaluation,
                      top={"data_dir": BAL})
        cfg.setdefault("data", {})["degree_balance"] = True
        write(f"{name}.yaml", cfg, header)
        return cfg

    bal("v3_graphtoken.yaml", "bal_data", "generate the degree-balanced dataset (and nothing else)",
        model={"graph_dropout": 0.0, "graph_aggregation": "sum"})
    # existing models, no retraining, evaluated on the balanced static test
    for tag, base, src, extra in (
        ("gt_sum", "v3_graphtoken.yaml", "gt_sum", {}),
        ("gt_warm_full", "v3_graphtoken.yaml", "gt_warm_full", {"gnn_checkpoint": "outputs/audit/pre_sum/gnn/gnn.pt"}),
        ("tea_sum_random", "v3_tea.yaml", "tea_sum_random", {"gnn_init": "random"}),
    ):
        cfg = bal(base, f"bal_eval_{tag}", f"{tag} (trained on the original data) evaluated on the degree-balanced data",
                  model={**sum_model, **extra, "checkpoint": f"outputs/audit/{src}/projector/checkpoint-final"})
        if tag == "tea_sum_random":
            cfg["model"].pop("gnn_checkpoint", None)
            write(f"bal_eval_{tag}.yaml", cfg, f"{tag} evaluated on the degree-balanced data")
    # retrained on the balanced training split
    bal("v3_graphtoken.yaml", "bal_gt_sum", "GraphToken (sum, scratch) trained on degree-balanced data",
        model=gt_sum_model, training=gt_sum_training)
    bal("v3_exact2x_graphtoken.yaml", "bal_gt_sum_exact2x", "bal_gt_sum: multi-turn evaluation",
        model={**gt_sum_model, "checkpoint": "outputs/audit/bal_gt_sum/projector/checkpoint-final"},
        training=gt_sum_training, evaluation={"conditions": GRAPH_CONDITIONS})
    bal("v3_tea.yaml", "bal_pre_sum", "sum-aggregation GNN pretrained on the degree-balanced training graphs",
        model={**sum_model, "gnn_checkpoint": "outputs/audit/bal_pre_sum/gnn/gnn.pt"},
        training={"gnn_epochs": 10, "gnn_learning_rate": 0.001, "contrastive_temperature": 0.07, "pretrain_dropout": 0.0})
    bal("v3_graphtoken.yaml", "bal_gt_warm_full", "GraphToken warm start on degree-balanced data",
        model={**gt_sum_model, "gnn_checkpoint": "outputs/audit/bal_pre_sum/gnn/gnn.pt"}, training=gt_sum_training)
    bal("v3_exact2x_graphtoken.yaml", "bal_gt_warm_full_exact2x", "bal_gt_warm_full: multi-turn evaluation",
        model={**gt_sum_model, "gnn_checkpoint": "outputs/audit/bal_pre_sum/gnn/gnn.pt",
               "checkpoint": "outputs/audit/bal_gt_warm_full/projector/checkpoint-final"},
        training=gt_sum_training, evaluation={"conditions": GRAPH_CONDITIONS})

    # ---- text-only baselines under the new parser for every model (no mixing of parsers) ------
    variant("v3_exact2x_graphtoken.yaml", "textonly_gt_old",
            "question_only / token_matched_history for the old GraphToken backend, new parser",
            model={"checkpoint": GT_CKPT_OLD, "gnn_checkpoint": "outputs/v3_tea/gnn/gnn.pt"},
            evaluation={"conditions": ["question_only", "token_matched_history"]})
    variant("v3_exact2x_soft_prompt.yaml", "textonly_soft_prompt",
            "soft-prompt backend with the new parser (graph-free conditions)",
            model={"checkpoint": SP_CKPT},
            evaluation={"conditions": ["soft_prompt", "soft_prompt_no_history"]})

    # ---- second audit: pretraining variants (pretrain only; selected by probe_gnn.py) -----
    base_pre = {"gnn_epochs": 10, "gnn_learning_rate": 0.001, "contrastive_temperature": 0.07}
    pre_variants = {
        "pre_base": ("as published (dropout 0.5, T 0.07, 10 ep), now with a working optimiser", {}, {}),
        "pre_nodrop": ("no GNN dropout during pretraining", {"pretrain_dropout": 0.0}, {}),
        "pre_nodrop_t02": ("no dropout, temperature 0.2", {"pretrain_dropout": 0.0, "contrastive_temperature": 0.2}, {}),
        "pre_nodrop_lr3": ("no dropout, lr 3e-3", {"pretrain_dropout": 0.0, "gnn_learning_rate": 0.003}, {}),
        "pre_attrs": ("target without the station name, no dropout",
                      {"pretrain_dropout": 0.0, "contrastive_target": "attrs_only"}, {}),
        "pre_status": ("target = text + 4x status embedding, no dropout",
                       {"pretrain_dropout": 0.0, "contrastive_target": "status_weighted"}, {}),
        "pre_long": ("no dropout, 40 epochs", {"pretrain_dropout": 0.0, "gnn_epochs": 40}, {}),
        "pre_sum": ("sum aggregation, no dropout (for the warm-start GraphToken)",
                    {"pretrain_dropout": 0.0}, {"graph_aggregation": "sum"}),
        "pre_deep_base": ("6-layer GNN, as published", {}, {"graph_layers": 6}),
        "pre_deep_nodrop": ("6-layer GNN, no dropout", {"pretrain_dropout": 0.0}, {"graph_layers": 6}),
    }
    for name, (header, training, model) in pre_variants.items():
        variant("v3_tea.yaml", name, f"GNN pretraining variant: {header}",
                model={**model, "gnn_checkpoint": f"outputs/audit/{name}/gnn/gnn.pt"},
                training={**base_pre, **training})

    # ---- second audit: TEA with a frozen random GNN (the no-pretraining control) ------------
    cfg = variant("v3_tea.yaml", "tea_randomgnn",
                  "TEA with a seeded random GNN, frozen, never pretrained (rank 4 control)",
                  model={"gnn_init": "random"})
    del cfg["model"]["gnn_checkpoint"]
    write("tea_randomgnn.yaml", cfg, "TEA with a seeded random GNN, frozen, never pretrained (rank 4 control)")
    ex = variant("v3_exact2x_tea.yaml", "tea_randomgnn_exact2x", "tea_randomgnn: multi-turn evaluation",
                 model={"checkpoint": "outputs/audit/tea_randomgnn/projector/checkpoint-final"},
                 evaluation={"conditions": GRAPH_CONDITIONS})
    ex["model"].pop("gnn_checkpoint", None)
    write("tea_randomgnn_exact2x.yaml", ex, "tea_randomgnn: multi-turn evaluation")

    # ---- rank 6: full multi-turn re-evaluation with raw outputs ----------------------------
    variant("v3_exact2x_tea.yaml", "reeval_tea", "TEA multi-turn re-evaluation (raw outputs, new parser)",
            evaluation={"conditions": GRAPH_CONDITIONS})
    variant("v3_exact2x_graphtoken.yaml", "reeval_gt_old",
            "original ('GraphToken' = frozen-GNN second TEA run) multi-turn re-evaluation",
            model={"checkpoint": GT_CKPT_OLD, "gnn_checkpoint": "outputs/v3_tea/gnn/gnn.pt"},
            evaluation={"conditions": GRAPH_CONDITIONS})
    variant("v3_exact2x_soft_prompt.yaml", "reeval_soft_prompt",
            "soft prompt multi-turn re-evaluation (raw outputs, new parser)",
            model={"checkpoint": SP_CKPT},
            evaluation={"conditions": ["soft_prompt", "soft_prompt_no_history"]})
    # Model-free baselines, once (they do not depend on any model).
    variant("v3_exact2x_tea.yaml", "reeval_model_free", "model-free baselines, computed once",
            evaluation={"conditions": MODEL_FREE})


if __name__ == "__main__":
    main()
